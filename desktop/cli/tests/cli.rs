//! End-to-end tests for the `my-linux-theme` binary.
//!
//! Every test runs against its own temporary root, so the real desktop
//! configuration is never touched.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const BIN: &str = env!("CARGO_BIN_EXE_my-linux-theme");

struct TempRoot {
    path: PathBuf,
}

impl TempRoot {
    fn new(name: &str) -> Self {
        let path =
            std::env::temp_dir().join(format!("my-linux-cli-{}-{}", std::process::id(), name));

        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).unwrap();

        Self { path }
    }

    fn path(&self) -> &Path {
        &self.path
    }

    fn join(&self, relative: &str) -> PathBuf {
        self.path.join(relative)
    }

    fn write(&self, relative: &str, contents: &str) {
        fs::write(self.join(relative), contents).unwrap();
    }

    fn read(&self, relative: &str) -> String {
        fs::read_to_string(self.join(relative)).unwrap()
    }
}

impl Drop for TempRoot {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

fn run(root: &Path, args: &[&str]) -> Output {
    Command::new(BIN)
        .arg("--root")
        .arg(root)
        .args(args)
        .output()
        .expect("the CLI binary should start")
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).to_string()
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).to_string()
}

const ORIGINAL: &str = "/* Original test Waybar configuration */\n";

#[test]
fn lists_the_builtin_themes() {
    let root = TempRoot::new("list");
    let output = run(root.path(), &["list"]);

    assert!(output.status.success());

    let out = stdout(&output);

    for theme in ["futuristic", "minimal", "cyberpunk", "nature"] {
        assert!(out.contains(theme), "list should mention {theme}");
    }
}

#[test]
fn info_and_preview_show_the_palette() {
    let root = TempRoot::new("preview");

    let info = run(root.path(), &["info", "cyberpunk"]);
    assert!(info.status.success());

    let info_out = stdout(&info);
    assert!(info_out.contains("Cyberpunk"));
    assert!(info_out.contains("#0C0812"));
    assert!(info_out.contains("#FF235A"));

    let preview = run(root.path(), &["preview", "cyberpunk"]);
    assert!(preview.status.success());
    assert!(stdout(&preview).contains("Cyberpunk"));
}

#[test]
fn render_prints_waybar_css() {
    let root = TempRoot::new("render");
    let output = run(root.path(), &["render", "cyberpunk"]);

    assert!(output.status.success());

    let out = stdout(&output);
    assert!(out.contains("@define-color main-bg #0C0812;"));
    assert!(out.contains("@define-color wb-act-bg #FF235A;"));
}

#[test]
fn apply_installs_the_theme_and_backs_up_the_original() {
    let root = TempRoot::new("apply");
    root.write("waybar.css", ORIGINAL);

    let output = run(root.path(), &["apply", "cyberpunk"]);
    assert!(output.status.success(), "{}", stderr(&output));

    assert_eq!(root.read("backups/waybar.css.original"), ORIGINAL);

    let installed = root.read("waybar.css");
    assert!(installed.contains("#FF235A"));
    assert!(installed.contains("Generated by My Linux Theme Engine"));

    assert_eq!(root.read("state/active-theme").trim(), "cyberpunk");
}

#[test]
fn apply_without_an_existing_configuration_creates_no_backup() {
    let root = TempRoot::new("apply-fresh");

    let output = run(root.path(), &["apply", "nature"]);
    assert!(output.status.success(), "{}", stderr(&output));

    assert!(stdout(&output).contains("none (there was no previous configuration)"));
    assert!(!root.join("backups/waybar.css.original").exists());
    assert!(root.read("waybar.css").contains("#6EBE5A"));
}

#[test]
fn repeated_apply_keeps_the_first_original_backup() {
    let root = TempRoot::new("apply-repeat");
    root.write("waybar.css", ORIGINAL);

    for _ in 0..3 {
        let output = run(root.path(), &["apply", "cyberpunk"]);
        assert!(output.status.success(), "{}", stderr(&output));
        assert_eq!(root.read("backups/waybar.css.original"), ORIGINAL);
    }
}

#[test]
fn switching_themes_replaces_the_configuration_but_keeps_the_backup() {
    let root = TempRoot::new("apply-switch");
    root.write("waybar.css", ORIGINAL);

    assert!(run(root.path(), &["apply", "cyberpunk"]).status.success());
    assert!(run(root.path(), &["apply", "nature"]).status.success());

    let installed = root.read("waybar.css");

    assert!(installed.contains("#6EBE5A"));
    assert!(!installed.contains("#FF235A"));
    assert_eq!(root.read("backups/waybar.css.original"), ORIGINAL);
    assert_eq!(root.read("state/active-theme").trim(), "nature");
}

#[test]
fn restore_returns_the_original_configuration() {
    let root = TempRoot::new("restore");
    root.write("waybar.css", ORIGINAL);

    assert!(run(root.path(), &["apply", "cyberpunk"]).status.success());

    let output = run(root.path(), &["restore"]);
    assert!(output.status.success(), "{}", stderr(&output));

    assert_eq!(root.read("waybar.css"), ORIGINAL);
    assert_eq!(root.read("backups/waybar.css.original"), ORIGINAL);
    assert!(!root.join("state/active-theme").exists());
}

#[test]
fn restore_without_a_backup_fails_clearly() {
    let root = TempRoot::new("restore-missing");

    let output = run(root.path(), &["restore"]);

    assert!(!output.status.success());
    assert!(stderr(&output).contains("No backup found"));
    assert!(!root.join("waybar.css").exists());
}

#[test]
fn status_reports_the_active_theme_and_installation_state() {
    let root = TempRoot::new("status");

    let before = run(root.path(), &["status"]);
    assert!(before.status.success());

    let before_out = stdout(&before);
    assert!(before_out.contains("Active theme:     none"));
    assert!(before_out.contains("Original backup:  missing"));

    root.write("waybar.css", ORIGINAL);
    assert!(run(root.path(), &["apply", "minimal"]).status.success());

    let after = run(root.path(), &["status"]);
    let after_out = stdout(&after);

    assert!(after_out.contains("Active theme:     minimal"));
    assert!(after_out.contains("Original backup:  present"));
}

#[test]
fn export_writes_css_to_the_requested_file() {
    let root = TempRoot::new("export");
    let target = root.join("css/cyberpunk.css");

    let output = run(
        root.path(),
        &["export", "cyberpunk", target.to_str().unwrap()],
    );

    assert!(output.status.success(), "{}", stderr(&output));
    assert!(fs::read_to_string(&target).unwrap().contains("#0C0812"));
}

#[test]
fn unknown_theme_and_unknown_command_fail() {
    let root = TempRoot::new("errors");

    let theme = run(root.path(), &["apply", "does-not-exist"]);
    assert!(!theme.status.success());
    assert!(stderr(&theme).contains("Unknown theme"));

    let command = run(root.path(), &["teleport"]);
    assert!(!command.status.success());
    assert!(stderr(&command).contains("Unknown command"));
}

#[test]
fn rollback_undoes_the_last_apply() {
    let root = TempRoot::new("rollback");
    root.write("waybar.css", ORIGINAL);

    assert!(run(root.path(), &["apply", "cyberpunk"]).status.success());
    let cyberpunk = root.read("waybar.css");

    assert!(run(root.path(), &["apply", "nature"]).status.success());
    assert!(root.read("waybar.css").contains("#6EBE5A"));

    let output = run(root.path(), &["rollback"]);
    assert!(output.status.success(), "{}", stderr(&output));

    assert_eq!(root.read("waybar.css"), cyberpunk);
    assert_eq!(root.read("state/active-theme").trim(), "cyberpunk");
    assert_eq!(root.read("backups/waybar.css.original"), ORIGINAL);
    assert!(stdout(&run(root.path(), &["status"])).contains("unmodified"));
}

#[test]
fn rollback_without_a_previous_state_fails() {
    let root = TempRoot::new("rollback-missing");

    let output = run(root.path(), &["rollback"]);

    assert!(!output.status.success());
    assert!(stderr(&output).contains("No backup found"));
}

#[test]
fn history_records_every_operation() {
    let root = TempRoot::new("history");
    root.write("waybar.css", ORIGINAL);

    assert!(run(root.path(), &["apply", "cyberpunk"]).status.success());
    assert!(run(root.path(), &["apply", "nature"]).status.success());
    assert!(run(root.path(), &["restore"]).status.success());

    let output = run(root.path(), &["history"]);
    assert!(output.status.success());

    let out = stdout(&output);

    assert!(out.contains("cyberpunk"));
    assert!(out.contains("nature"));
    assert!(out.contains("restore"));
    assert!(out.contains("waybar.css"));
}

#[test]
fn history_is_empty_before_any_operation() {
    let root = TempRoot::new("history-empty");
    let output = run(root.path(), &["history"]);

    assert!(output.status.success());
    assert!(stdout(&output).contains("No installation history"));
}

