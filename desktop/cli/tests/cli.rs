//! End-to-end tests for the `my-linux-theme` binary.
//!
//! Every test runs against its own temporary root, so the real desktop
//! configuration is never touched.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const BIN: &str = env!("CARGO_BIN_EXE_my-linux-theme");

struct TempRoot {
    path: PathBuf,
}

impl TempRoot {
    fn new(name: &str) -> Self {
        let path =
            std::env::temp_dir().join(format!("my-linux-cli-{}-{}", std::process::id(), name));

        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).unwrap();

        Self { path }
    }

    fn path(&self) -> &Path {
        &self.path
    }

    fn join(&self, relative: &str) -> PathBuf {
        self.path.join(relative)
    }

    fn write(&self, relative: &str, contents: &str) {
        fs::write(self.join(relative), contents).unwrap();
    }

    fn read(&self, relative: &str) -> String {
        fs::read_to_string(self.join(relative)).unwrap()
    }
}

impl Drop for TempRoot {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

fn run(root: &Path, args: &[&str]) -> Output {
    Command::new(BIN)
        .arg("--root")
        .arg(root)
        .args(args)
        .output()
        .expect("the CLI binary should start")
}

/// Runs the CLI with an isolated user theme directory.
fn run_with_user_themes(root: &Path, args: &[&str], user_themes: &Path) -> Output {
    Command::new(BIN)
        .arg("--root")
        .arg(root)
        .args(args)
        .env("MY_LINUX_USER_THEMES", user_themes)
        .output()
        .expect("the CLI binary should start")
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).to_string()
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).to_string()
}

const ORIGINAL: &str = "/* Original test Waybar configuration */\n";

#[test]
fn lists_the_builtin_themes() {
    let root = TempRoot::new("list");
    let output = run(root.path(), &["list"]);

    assert!(output.status.success());

    let out = stdout(&output);

    for theme in ["futuristic", "minimal", "cyberpunk", "nature"] {
        assert!(out.contains(theme), "list should mention {theme}");
    }
}

