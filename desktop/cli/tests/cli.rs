#[test]
fn apply_installs_the_theme_and_backs_up_the_original() {
    let root = TempRoot::new("apply");
    root.write("waybar.css", ORIGINAL);

    let output = run(root.path(), &["apply", "cyberpunk"]);
    assert!(output.status.success(), "{}", stderr(&output));

    assert_eq!(root.read("backups/waybar.css.original"), ORIGINAL);

    let installed = root.read("waybar.css");
    assert!(installed.contains("#FF235A"));
    assert!(installed.contains("Generated by My Linux Theme Engine"));

    assert_eq!(root.read("state/active-theme").trim(), "cyberpunk");
}

