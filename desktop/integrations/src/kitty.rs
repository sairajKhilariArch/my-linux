//! Kitty terminal integration.

use theme_engine::{Color, LoadedTheme};

use crate::{Integration, RenderError, require};

pub struct Kitty;

impl Integration for Kitty {
    fn id(&self) -> &'static str {
        "kitty"
    }

    fn name(&self) -> &'static str {
        "Kitty"
    }

    fn relative_path(&self) -> &'static str {
        "kitty/my-linux.conf"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["kitty"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("kitty", content, "background ")?;
        require("kitty", content, "foreground ")?;
        require("kitty", content, "color15 ")?;

        if content.contains('{') {
            return Err(RenderError::Invalid(
                "kitty configuration must not contain blocks".to_string(),
            ));
        }

        Ok(())
    }

    fn reload_commands(&self) -> &'static [&'static [&'static str]] {
        &[&["pkill", "-USR1", "-x", "kitty"]]
    }
}

/// The 16 terminal colours derived from the theme palette.
fn terminal_palette(theme: &LoadedTheme) -> [Color; 16] {
    let colors = &theme.colors;

    [
        colors.background,
        colors.error,
        colors.success,
        colors.warning,
        colors.secondary,
        colors.primary,
        colors.hover,
        colors.text_muted,
        colors.border,
        colors.error.lighten(0.25),
        colors.success.lighten(0.25),
        colors.warning.lighten(0.25),
        colors.secondary.lighten(0.25),
        colors.primary.lighten(0.25),
        colors.surface_alt,
        colors.text,
    ]
}

/// Generates a Kitty configuration from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n");
    output.push_str("# Include this file from your own kitty.conf:\n");
    output.push_str("#   include ~/.config/kitty/my-linux.conf\n\n");

    output.push_str(&format!("background {}\n", colors.background.to_hex()));
    output.push_str(&format!("foreground {}\n", colors.text.to_hex()));
    output.push_str(&format!("cursor {}\n", colors.primary.to_hex()));
    output.push_str(&format!(
        "cursor_text_color {}\n",
        colors.background.to_hex()
    ));
    output.push_str(&format!(
        "selection_background {}\n",
        colors.surface_alt.to_hex()
    ));
    output.push_str(&format!("selection_foreground {}\n", colors.text.to_hex()));
    output.push_str(&format!("url_color {}\n", colors.secondary.to_hex()));
    output.push_str(&format!(
        "active_border_color {}\n",
        colors.primary.to_hex()
    ));
    output.push_str(&format!(
        "inactive_border_color {}\n",
        colors.border.to_hex()
    ));
    output.push_str(&format!(
        "active_tab_background {}\n",
        colors.primary.to_hex()
    ));
    output.push_str(&format!(
        "active_tab_foreground {}\n",
        colors.background.to_hex()
    ));
    output.push_str(&format!(
        "inactive_tab_background {}\n",
        colors.surface.to_hex()
    ));
    output.push_str(&format!(
        "inactive_tab_foreground {}\n",
        colors.text_muted.to_hex()
    ));
    output.push_str(&format!(
        "tab_bar_background {}\n\n",
        colors.background.to_hex()
    ));

    for (index, color) in terminal_palette(theme).iter().enumerate() {
        output.push_str(&format!("color{index} {}\n", color.to_hex()));
    }

    output.push_str(&format!("\nfont_family {}\n", theme.typography.mono_family));
    output.push_str("bold_font auto\n");
    output.push_str("italic_font auto\n");
    output.push_str(&format!("font_size {}.0\n", theme.typography.font_size));
    output.push_str(&format!("window_padding_width {}\n", theme.metrics.spacing));
    output.push_str("background_opacity 1.0\n");
    output.push_str("cursor_shape beam\n");
    output.push_str("cursor_blink_interval 0.5\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_terminal_colours() {
        let conf = render(&theme());

        assert!(conf.contains("background #0C0812"));
        assert!(conf.contains("foreground #FFF0FA"));
        assert!(conf.contains("cursor #FF235A"));
        assert!(conf.contains("color0 #0C0812"));
        assert!(conf.contains("color15 #FFF0FA"));
        assert!(conf.contains("font_family JetBrainsMono Nerd Font"));
    }

    #[test]
    fn renders_all_sixteen_colours() {
        let conf = render(&theme());

        for index in 0..16 {
            assert!(
                conf.contains(&format!("color{index} #")),
                "missing color{index}"
            );
        }
    }

    #[test]
    fn validates_kitty_configuration() {
        assert!(Kitty.validate(&render(&theme())).is_ok());
        assert!(Kitty.validate("background #000\nforeground #fff").is_err());
    }
}
