//! Zsh prompt and completion colouring.
//!
//! A dedicated file is generated so the user's `.zshrc` is never rewritten:
//!
//! ```zsh
//! source ~/.config/zsh/my-linux.zsh
//! ```

use theme_engine::{Color, LoadedTheme};

use crate::{Integration, RenderError, require};

pub struct Zsh;

impl Integration for Zsh {
    fn id(&self) -> &'static str {
        "zsh"
    }

    fn name(&self) -> &'static str {
        "Zsh prompt"
    }

    fn relative_path(&self) -> &'static str {
        "zsh/my-linux.zsh"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["zsh"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("zsh", content, "PROMPT=")?;
        require("zsh", content, "MY_LINUX_ACCENT=")?;
        require("zsh", content, "list-colors")?;

        Ok(())
    }
}

/// Approximate 256-colour index for a truecolor value.
fn ansi256(color: Color) -> u8 {
    let level = |value: u8| -> u8 {
        let scaled = f32::from(value) / 255.0 * 5.0;

        scaled.round() as u8
    };

    16 + 36 * level(color.red) + 6 * level(color.green) + level(color.blue)
}

/// Generates a Zsh theme fragment from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let c = &theme.colors;

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n");
    output.push_str("# Source it after your prompt setup:\n");
    output.push_str("#   source ~/.config/zsh/my-linux.zsh\n\n");

    output.push_str(&format!("MY_LINUX_BG='{}'\n", c.background.to_hex()));
    output.push_str(&format!("MY_LINUX_FG='{}'\n", c.text.to_hex()));
    output.push_str(&format!("MY_LINUX_MUTED='{}'\n", c.text_muted.to_hex()));
    output.push_str(&format!("MY_LINUX_ACCENT='{}'\n", c.primary.to_hex()));
    output.push_str(&format!("MY_LINUX_SECONDARY='{}'\n", c.secondary.to_hex()));
    output.push_str(&format!("MY_LINUX_SUCCESS='{}'\n", c.success.to_hex()));
    output.push_str(&format!("MY_LINUX_WARNING='{}'\n", c.warning.to_hex()));
    output.push_str(&format!("MY_LINUX_ERROR='{}'\n", c.error.to_hex()));
    output.push_str("export MY_LINUX_BG MY_LINUX_FG MY_LINUX_MUTED MY_LINUX_ACCENT\n");
    output
        .push_str("export MY_LINUX_SECONDARY MY_LINUX_SUCCESS MY_LINUX_WARNING MY_LINUX_ERROR\n\n");

    output.push_str("# Completion listing.\n");
    output.push_str("zstyle ':completion:*' list-colors \\\n");
    output.push_str(&format!(
        "    \"di=38;5;{}\" \"ln=38;5;{}\" \"so=38;5;{}\" \\\n",
        ansi256(c.primary),
        ansi256(c.secondary),
        ansi256(c.success)
    ));
    output.push_str(&format!(
        "    \"ex=38;5;{}\" \"pi=38;5;{}\" \"cd=38;5;{}\" \\\n",
        ansi256(c.success),
        ansi256(c.warning),
        ansi256(c.secondary)
    ));
    output.push_str(&format!(
        "    \"*.tar=38;5;{}\" \"*.zip=38;5;{}\" \"*.png=38;5;{}\"\n\n",
        ansi256(c.error),
        ansi256(c.warning),
        ansi256(c.primary)
    ));

    output.push_str("# Matched substring in completion menus.\n");
    output.push_str(&format!(
        "zstyle ':completion:*' match-messages yes\nzstyle ':completion:*:descriptions' format '%F{{{}}}-- %d --%f'\n\n",
        c.text_muted.to_hex()
    ));

    output.push_str("# Autosuggestions, when zsh-autosuggestions is loaded after this file.\n");
    output.push_str("ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE=\"fg=${MY_LINUX_MUTED}\"\n\n");

    output.push_str("# Prompt: user@host path, then the accent chevron.\n");
    output.push_str(&format!(
        "PROMPT=\"%F{{{}}}%n%f%F{{{}}}@%m%f %F{{{}}}%~%f\n%F{{{}}}❯%f \"\n",
        c.primary.to_hex(),
        c.text_muted.to_hex(),
        c.secondary.to_hex(),
        c.primary.to_hex()
    ));
    output.push_str("PROMPT2=\"%F{");
    output.push_str(&c.text_muted.to_hex());
    output.push_str("}%_%f \"\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_prompt_and_completion_colours() {
        let script = render(&theme());

        assert!(script.contains("MY_LINUX_ACCENT='#FF235A'"));
        assert!(script.contains("PROMPT=\"%F{#FF235A}%n%f"));
        assert!(script.contains("list-colors"));
        assert!(script.contains("\"di=38;5;"));
    }

    #[test]
    fn converts_truecolor_to_ansi_256() {
        // Pure black and pure white land on the cube corners.
        assert_eq!(ansi256(Color::new(0, 0, 0)), 16);
        assert_eq!(ansi256(Color::new(255, 255, 255)), 231);
    }

    #[test]
    fn validates_zsh_fragment() {
        assert!(Zsh.validate(&render(&theme())).is_ok());
        assert!(Zsh.validate("echo hello\n").is_err());
    }
}
