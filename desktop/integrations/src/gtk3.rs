//! GTK 3 application styling.
//!
//! GTK reads `~/.config/gtk-3.0/gtk.css`. My Linux never rewrites that file;
//! it generates `~/.config/gtk-3.0/my-linux.css`, which the user's own
//! stylesheet imports.

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Gtk3;

impl Integration for Gtk3 {
    fn id(&self) -> &'static str {
        "gtk3"
    }

    fn name(&self) -> &'static str {
        "GTK 3"
    }

    fn relative_path(&self) -> &'static str {
        "gtk-3.0/my-linux.css"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["gtk3-demo"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("gtk3", content, "@define-color my_linux_bg")?;
        require("gtk3", content, "background-color: @my_linux_bg")?;
        validate_braces(content)
    }
}

/// Generates a GTK 3 stylesheet from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let c = &theme.colors;

    let mut output = String::new();

    output.push_str("/* Generated by My Linux Theme Engine. Do not edit manually. */\n");
    output.push_str("/* Import it from your own ~/.config/gtk-3.0/gtk.css:  */\n");
    output.push_str("/*   @import url(\"my-linux.css\");                     */\n\n");

    for (name, color) in [
        ("my_linux_bg", c.background),
        ("my_linux_surface", c.surface),
        ("my_linux_surface_alt", c.surface_alt),
        ("my_linux_fg", c.text),
        ("my_linux_muted", c.text_muted),
        ("my_linux_border", c.border),
        ("my_linux_primary", c.primary),
        ("my_linux_secondary", c.secondary),
        ("my_linux_hover", c.hover),
        ("my_linux_selected", c.selected),
        ("my_linux_success", c.success),
        ("my_linux_warning", c.warning),
        ("my_linux_error", c.error),
    ] {
        output.push_str(&format!("@define-color {name} {};\n", color.to_hex()));
    }

    output.push('\n');

    output.push_str("window, .background {\n");
    output.push_str("    background-color: @my_linux_bg;\n");
    output.push_str("    color: @my_linux_fg;\n");
    output.push_str("}\n\n");

    output.push_str("headerbar, .titlebar {\n");
    output.push_str("    background-color: @my_linux_surface;\n");
    output.push_str("    background-image: none;\n");
    output.push_str("    color: @my_linux_fg;\n");
    output.push_str("    border-bottom: 1px solid @my_linux_border;\n");
    output.push_str("    box-shadow: none;\n");
    output.push_str("}\n\n");

    output.push_str("button {\n");
    output.push_str("    background-image: none;\n");
    output.push_str("    background-color: @my_linux_surface_alt;\n");
    output.push_str("    color: @my_linux_fg;\n");
    output.push_str("    border: 1px solid @my_linux_border;\n");
    output.push_str("    border-radius: 6px;\n");
    output.push_str("    padding: 4px 10px;\n");
    output.push_str("}\n\n");

    output.push_str("button:hover {\n");
    output.push_str("    background-color: @my_linux_hover;\n");
    output.push_str("    color: @my_linux_bg;\n");
    output.push_str("}\n\n");

    output.push_str("button:active, button:checked {\n");
    output.push_str("    background-color: @my_linux_primary;\n");
    output.push_str("    color: @my_linux_bg;\n");
    output.push_str("}\n\n");

    output.push_str("entry, spinbutton, textview, textview text {\n");
    output.push_str("    background-color: @my_linux_surface;\n");
    output.push_str("    color: @my_linux_fg;\n");
    output.push_str("    border: 1px solid @my_linux_border;\n");
    output.push_str("    border-radius: 6px;\n");
    output.push_str("}\n\n");

    output.push_str("entry:focus, entry:focus-within {\n");
    output.push_str("    border-color: @my_linux_primary;\n");
    output.push_str("}\n\n");

    output.push_str("selection, *:selected {\n");
    output.push_str("    background-color: @my_linux_primary;\n");
    output.push_str("    color: @my_linux_bg;\n");
    output.push_str("}\n\n");

    output.push_str("menu, popover, popover.background {\n");
    output.push_str("    background-color: @my_linux_surface_alt;\n");
    output.push_str("    color: @my_linux_fg;\n");
    output.push_str("    border: 1px solid @my_linux_border;\n");
    output.push_str("}\n\n");

    output.push_str("menuitem:hover, popover modelbutton:hover {\n");
    output.push_str("    background-color: @my_linux_primary;\n");
    output.push_str("    color: @my_linux_bg;\n");
    output.push_str("}\n\n");

    output.push_str("tooltip, tooltip.background {\n");
    output.push_str("    background-color: @my_linux_surface_alt;\n");
    output.push_str("    color: @my_linux_fg;\n");
    output.push_str("    border: 1px solid @my_linux_primary;\n");
    output.push_str("    border-radius: 6px;\n");
    output.push_str("}\n\n");

    output.push_str("scrollbar slider {\n");
    output.push_str("    background-color: @my_linux_border;\n");
    output.push_str("    border-radius: 8px;\n");
    output.push_str("    min-width: 6px;\n");
    output.push_str("    min-height: 6px;\n");
    output.push_str("}\n\n");

    output.push_str("scrollbar slider:hover {\n");
    output.push_str("    background-color: @my_linux_primary;\n");
    output.push_str("}\n\n");

    output.push_str("progressbar progress {\n");
    output.push_str("    background-color: @my_linux_primary;\n");
    output.push_str("}\n\n");

    output.push_str("switch:checked, checkbutton check:checked, radiobutton radio:checked {\n");
    output.push_str("    background-color: @my_linux_primary;\n");
    output.push_str("    color: @my_linux_bg;\n");
    output.push_str("}\n\n");

    output.push_str("notebook tab:checked {\n");
    output.push_str("    background-color: @my_linux_surface_alt;\n");
    output.push_str("    color: @my_linux_primary;\n");
    output.push_str("}\n\n");

    output.push_str("link, *:link {\n");
    output.push_str("    color: @my_linux_secondary;\n");
    output.push_str("}\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_theme_colours_and_widget_rules() {
        let css = render(&theme());

        assert!(css.contains("@define-color my_linux_bg #0C0812;"));
        assert!(css.contains("@define-color my_linux_primary #FF235A;"));
        assert!(css.contains("button:hover"));
        assert!(css.contains("selection, *:selected"));
    }

    #[test]
    fn validates_gtk3_stylesheet() {
        assert!(Gtk3.validate(&render(&theme())).is_ok());
        assert!(Gtk3.validate("@define-color my_linux_bg #000;").is_err());
    }
}
