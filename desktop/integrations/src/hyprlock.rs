//! Lock screen integration (Hyprlock).

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Hyprlock;

impl Integration for Hyprlock {
    fn id(&self) -> &'static str {
        "hyprlock"
    }

    fn name(&self) -> &'static str {
        "Lock screen (Hyprlock)"
    }

    fn relative_path(&self) -> &'static str {
        "hyprlock/hyprlock.conf"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["hyprlock"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("hyprlock", content, "input-field {")?;
        require("hyprlock", content, "background {")?;
        validate_braces(content)
    }

    fn reload_commands(&self) -> &'static [&'static [&'static str]] {
        // Hyprlock reads its configuration when it starts.
        &[]
    }
}

fn rgba(color: theme_engine::Color, alpha: &str) -> String {
    format!(
        "rgba({:02X}{:02X}{:02X}{})",
        color.red, color.green, color.blue, alpha
    )
}

/// Generates a Hyprlock configuration from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n\n");

    output.push_str("background {\n");
    output.push_str(&format!("    color = {}\n", rgba(colors.background, "ff")));
    output.push_str("    blur_passes = 2\n");
    output.push_str("}\n\n");

    output.push_str("label {\n");
    output.push_str("    text = $TIME\n");
    output.push_str(&format!("    color = {}\n", rgba(colors.text, "ff")));
    output.push_str("    font_size = 72\n");
    output.push_str("    font_family = JetBrainsMono Nerd Font\n");
    output.push_str("    position = 0, 160\n");
    output.push_str("    halign = center\n");
    output.push_str("    valign = center\n");
    output.push_str("}\n\n");

    output.push_str("label {\n");
    output.push_str("    text = $LAYOUT\n");
    output.push_str(&format!("    color = {}\n", rgba(colors.text_muted, "ff")));
    output.push_str("    font_size = 16\n");
    output.push_str("    position = 0, 120\n");
    output.push_str("    halign = center\n");
    output.push_str("    valign = center\n");
    output.push_str("}\n\n");

    output.push_str("input-field {\n");
    output.push_str("    size = 240, 44\n");
    output.push_str("    outline_thickness = 2\n");
    output.push_str("    dots_size = 0.2\n");
    output.push_str("    dots_spacing = 0.3\n");
    output.push_str(&format!(
        "    outer_color = {}\n",
        rgba(colors.primary, "ff")
    ));
    output.push_str(&format!(
        "    inner_color = {}\n",
        rgba(colors.surface, "ff")
    ));
    output.push_str(&format!("    font_color = {}\n", rgba(colors.text, "ff")));
    output.push_str("    fade_on_empty = false\n");
    output.push_str("    placeholder_text = <i>Password...</i>\n");
    output.push_str("    position = 0, -120\n");
    output.push_str("    halign = center\n");
    output.push_str("    valign = center\n");
    output.push_str("}\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_lock_screen() {
        let conf = render(&theme());

        assert!(conf.contains("background {"));
        assert!(conf.contains("input-field {"));
        assert!(conf.contains("$TIME"));
        assert!(conf.contains("FF235Aff"));
    }

    #[test]
    fn validates_hyprlock_output() {
        assert!(Hyprlock.validate(&render(&theme())).is_ok());
        assert!(Hyprlock.validate("input-field {").is_err());
    }
}
