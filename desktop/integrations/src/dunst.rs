//! Notification daemon integration (Dunst).

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Dunst;

impl Integration for Dunst {
    fn id(&self) -> &'static str {
        "dunst"
    }

    fn name(&self) -> &'static str {
        "Notifications (Dunst)"
    }

    fn relative_path(&self) -> &'static str {
        "dunst/dunstrc"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["dunst"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("dunst", content, "[urgency_critical]")?;
        require("dunst", content, "[urgency_normal]")?;
        require("dunst", content, "[global]")?;
        validate_braces(content)
    }

    fn reload_commands(&self) -> &'static [&'static [&'static str]] {
        &[&["dunstctl", "reload"]]
    }
}

/// Generates a Dunst configuration from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;
    let typography = theme.typography_for("dunst");
    let metrics = theme.metrics_for("dunst");

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n\n");

    output.push_str("[global]\n");
    output.push_str("    monitor = 0\n");
    output.push_str("    follow = mouse\n");
    output.push_str("    origin = top-right\n");
    output.push_str("    offset = 10x50\n");
    output.push_str("    width = 320\n");
    output.push_str(&format!(
        "    frame_color = \"{}\"\n",
        colors.border.to_hex()
    ));
    output.push_str("    separator_color = frame\n");
    output.push_str(&format!(
        "    font = {} {}\n",
        typography.mono_family, typography.font_size
    ));
    output.push_str(&format!("    corner_radius = {}\n", metrics.radius));
    output.push_str("    transparency = 0\n");
    output.push_str("    icon_position = left\n");
    output.push_str("    format = \"<b>%s</b>\\n%b\"\n\n");

    output.push_str("[urgency_low]\n");
    output.push_str(&format!(
        "    background = \"{}\"\n",
        colors.surface.to_hex()
    ));
    output.push_str(&format!(
        "    foreground = \"{}\"\n",
        colors.text_muted.to_hex()
    ));
    output.push_str(&format!(
        "    frame_color = \"{}\"\n",
        colors.border.to_hex()
    ));
    output.push_str("    timeout = 5\n\n");

    output.push_str("[urgency_normal]\n");
    output.push_str(&format!(
        "    background = \"{}\"\n",
        colors.surface_alt.to_hex()
    ));
    output.push_str(&format!("    foreground = \"{}\"\n", colors.text.to_hex()));
    output.push_str(&format!(
        "    frame_color = \"{}\"\n",
        colors.primary.to_hex()
    ));
    output.push_str("    timeout = 10\n\n");

    output.push_str("[urgency_critical]\n");
    output.push_str(&format!("    background = \"{}\"\n", colors.error.to_hex()));
    output.push_str(&format!(
        "    foreground = \"{}\"\n",
        colors.background.to_hex()
    ));
    output.push_str(&format!(
        "    frame_color = \"{}\"\n",
        colors.warning.to_hex()
    ));
    output.push_str("    timeout = 0\n");

    if let Some(apps) = theme.module_overrides("dunst") {
        for (app, style) in apps {
            output.push_str(&format!("\n[{app}]\n    appname = \"{app}\"\n"));

            if let Some(color) = style.background {
                output.push_str(&format!("    background = \"{}\"\n", color.to_hex()));
            }

            if let Some(color) = style.foreground {
                output.push_str(&format!("    foreground = \"{}\"\n", color.to_hex()));
            }

            if let Some(color) = style.border {
                output.push_str(&format!("    frame_color = \"{}\"\n", color.to_hex()));
            }
        }
    }

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::{Color, ModuleOverride, Registry, ThemeOverride};

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_per_application_rules() {
        let mut theme = theme();
        theme.overrides.insert(
            "dunst".to_string(),
            ThemeOverride {
                modules: [(
                    "slack".to_string(),
                    ModuleOverride {
                        background: Some(Color::new(0x20, 0x10, 0x30)),
                        foreground: Some(Color::new(0xFF, 0xFF, 0xFF)),
                        border: Some(Color::new(0xFF, 0x00, 0x00)),
                    },
                )]
                .into(),
                ..ThemeOverride::default()
            },
        );

        let config = render(&theme);

        assert!(config.contains("[slack]"));
        assert!(config.contains("appname = \"slack\""));
        assert!(config.contains("background = \"#201030\""));
        assert!(config.contains("frame_color = \"#FF0000\""));
    }

    #[test]
    fn renders_urgency_sections() {
        let conf = render(&theme());

        assert!(conf.contains("[global]"));
        assert!(conf.contains("[urgency_low]"));
        assert!(conf.contains("[urgency_normal]"));
        assert!(conf.contains("[urgency_critical]"));
        assert!(conf.contains("#FF235A"));
    }

    #[test]
    fn validates_dunst_output() {
        assert!(Dunst.validate(&render(&theme())).is_ok());
        assert!(Dunst.validate("[global]\n").is_err());
    }
}
