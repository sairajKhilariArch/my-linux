//! Launcher integration (Wofi).
//!
//! Wofi is a GTK-based Wayland launcher alternative to Rofi. My Linux writes a
//! normalised stylesheet that uses the theme colours, typography and geometry.

use theme_engine::Color;
use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Wofi;

impl Integration for Wofi {
    fn id(&self) -> &'static str {
        "wofi"
    }

    fn name(&self) -> &'static str {
        "Wofi launcher"
    }

    fn relative_path(&self) -> &'static str {
        "wofi/style.css"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["wofi"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("wofi", content, "window {")?;
        require("wofi", content, "#input {")?;
        validate_braces(content)
    }
}

fn hex(color: Color) -> String {
    color.to_hex()
}

/// Generates a Wofi stylesheet from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;
    let metrics = theme.metrics;

    let mut output = String::new();

    output.push_str("/* Generated by My Linux Theme Engine. Do not edit manually. */\n\n");

    output.push_str(&format!(
        "window {{\n    margin: 0px;\n    border: {}px solid {};\n    border-radius: {}px;\n    background-color: {};\n    color: {};\n    font-family: \"{}\";\n    font-size: {}px;\n}}\n\n",
        metrics.border_width,
        hex(colors.border),
        metrics.radius + 4,
        hex(colors.background),
        hex(colors.text),
        theme.typography.font_family,
        theme.typography.font_size
    ));

    output.push_str(&format!(
        "#input {{\n    margin: {}px;\n    padding: {}px;\n    border: 1px solid {};\n    border-radius: {}px;\n    background-color: {};\n    color: {};\n    caret-color: {};\n}}\n\n",
        metrics.spacing,
        metrics.spacing,
        hex(colors.border),
        metrics.radius,
        hex(colors.surface),
        hex(colors.text),
        hex(colors.primary)
    ));

    output.push_str(&format!(
        "#input:focus {{\n    border-color: {};\n    color: {};\n}}\n\n",
        hex(colors.primary),
        hex(colors.text)
    ));

    output.push_str(&format!(
        "#entry {{\n    padding: {}px;\n    color: {};\n}}\n\n",
        metrics.spacing,
        hex(colors.text)
    ));

    output.push_str(&format!(
        "#entry:selected {{\n    border-radius: {}px;\n    background-color: {};\n    color: {};\n}}\n\n",
        metrics.radius,
        hex(colors.primary),
        hex(colors.background)
    ));

    output.push_str(&format!(
        "#scroll {{\n    border-radius: {}px;\n    background-color: {};\n}}\n\n",
        metrics.radius,
        hex(colors.background)
    ));

    output.push_str(&format!(
        "#inner-box {{\n    border-radius: {}px;\n    background-color: {};\n}}\n\n",
        metrics.radius,
        hex(colors.surface)
    ));

    output.push_str(&format!(
        "tooltip {{\n    border: 1px solid {};\n    border-radius: {}px;\n    background-color: {};\n    color: {};\n}}\n",
        hex(colors.border),
        metrics.radius,
        hex(colors.surface_alt),
        hex(colors.text)
    ));

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_wofi_stylesheet() {
        let css = render(&theme());

        assert!(css.contains("background-color: #0C0812;"));
        assert!(css.contains("color: #FFF0FA;"));
        assert!(css.contains("#entry:selected"));
        assert!(css.contains("border-radius: 8px;"));
        assert!(css.contains("font-family: \"Inter\";"));
        assert!(Wofi.validate(&css).is_ok());
    }

    #[test]
    fn rejects_css_without_required_rules() {
        assert!(Wofi.validate("").is_err());
        assert!(Wofi.validate("window { color: red; }\n").is_err());
        assert!(Wofi.validate("window { }\n#input { ").is_err());
    }
}
