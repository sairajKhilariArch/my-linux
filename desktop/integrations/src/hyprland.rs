//! Hyprland configuration integration.
//!
//! Only a dedicated snippet is generated; the user's own `hyprland.conf` is
//! never rewritten. The snippet is meant to be sourced from it.

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Hyprland;

impl Integration for Hyprland {
    fn id(&self) -> &'static str {
        "hyprland"
    }

    fn name(&self) -> &'static str {
        "Hyprland"
    }

    fn relative_path(&self) -> &'static str {
        "hyprland/my-linux.conf"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["Hyprland", "hyprctl"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("hyprland", content, "col.active_border")?;
        require("hyprland", content, "col.inactive_border")?;
        validate_braces(content)
    }

    fn reload_commands(&self) -> &'static [&'static [&'static str]] {
        &[&["hyprctl", "reload"]]
    }
}

fn rgba(color: theme_engine::Color, alpha: &str) -> String {
    format!(
        "rgba({:02X}{:02X}{:02X}{})",
        color.red, color.green, color.blue, alpha
    )
}

/// Generates a Hyprland snippet from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n");
    output.push_str("# Source this file from your own ~/.config/hypr/hyprland.conf:\n");
    output.push_str("#   source = ~/.config/hypr/my-linux.conf\n\n");

    output.push_str("general {\n");
    output.push_str(&format!(
        "    col.active_border = {} {}\n",
        rgba(colors.active, "ff"),
        rgba(colors.hover, "ff")
    ));
    output.push_str(&format!(
        "    col.inactive_border = {}\n",
        rgba(colors.border, "ff")
    ));
    output.push_str("}\n\n");

    output.push_str("decoration {\n");
    output.push_str("    rounding = 10\n");
    output.push_str("    active_opacity = 1.0\n");
    output.push_str("    inactive_opacity = 0.94\n");
    output.push_str("    dim_inactive = false\n\n");

    output.push_str("    shadow {\n");
    output.push_str("        enabled = true\n");
    output.push_str("        range = 12\n");
    output.push_str("        render_power = 3\n");
    output.push_str(&format!(
        "        color = {}\n",
        rgba(colors.background, "ee")
    ));
    output.push_str("    }\n\n");

    output.push_str("    blur {\n");
    output.push_str("        enabled = true\n");
    output.push_str("        size = 6\n");
    output.push_str("        passes = 3\n");
    output.push_str("        new_optimizations = true\n");
    output.push_str("    }\n");
    output.push_str("}\n\n");

    output.push_str("misc {\n");
    output.push_str(&format!(
        "    background_color = {}\n",
        rgba(colors.background, "ff")
    ));
    output.push_str("}\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_borders_and_decorations() {
        let conf = render(&theme());

        assert!(conf.contains("col.active_border = rgba(FF235Aff) rgba(00E6FFff)"));
        assert!(conf.contains("col.inactive_border = rgba(592B50ff)"));
        assert!(conf.contains("rounding = 10"));
        assert!(conf.contains("blur {"));
        assert!(conf.contains("source = ~/.config/hypr/my-linux.conf"));
    }

    #[test]
    fn validates_snippet() {
        assert!(Hyprland.validate(&render(&theme())).is_ok());
        assert!(Hyprland.validate("general { }").is_err());
    }

    #[test]
    fn never_targets_the_main_hyprland_config() {
        assert_eq!(Hyprland.relative_path(), "hyprland/my-linux.conf");
    }
}
