//! Neovim colour scheme.
//!
//! The generated Lua module is loaded explicitly, so the user's own
//! `init.lua` stays untouched:
//!
//! ```lua
//! require("my-linux")
//! ```

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Neovim;

impl Integration for Neovim {
    fn id(&self) -> &'static str {
        "neovim"
    }

    fn name(&self) -> &'static str {
        "Neovim"
    }

    fn relative_path(&self) -> &'static str {
        "nvim/lua/my-linux.lua"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["nvim", "neovim"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("neovim", content, "nvim_set_hl")?;
        require("neovim", content, "colors_name")?;
        require("neovim", content, "return M")?;
        validate_braces(content)
    }
}

/// Generates a Neovim colour scheme module from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let c = &theme.colors;

    let mut output = String::new();

    output.push_str("-- Generated by My Linux Theme Engine. Do not edit manually.\n");
    output.push_str("-- Load it from ~/.config/nvim/init.lua:\n");
    output.push_str("--   require(\"my-linux\")\n\n");
    output.push_str("local M = {}\n\n");

    output.push_str("M.colors = {\n");
    for (name, color) in [
        ("bg", c.background),
        ("surface", c.surface),
        ("surface_alt", c.surface_alt),
        ("fg", c.text),
        ("muted", c.text_muted),
        ("border", c.border),
        ("primary", c.primary),
        ("secondary", c.secondary),
        ("hover", c.hover),
        ("selected", c.selected),
        ("success", c.success),
        ("warning", c.warning),
        ("error", c.error),
    ] {
        output.push_str(&format!("  {name} = \"{}\",\n", color.to_hex()));
    }
    output.push_str("}\n\n");

    output.push_str("local function hi(group, spec)\n");
    output.push_str("  vim.api.nvim_set_hl(0, group, spec)\n");
    output.push_str("end\n\n");

    output.push_str("function M.setup()\n");
    output.push_str("  vim.o.termguicolors = true\n");
    output.push_str("  vim.g.colors_name = \"my-linux\"\n\n");

    let highlights: &[(&str, &str)] = &[
        ("Normal", "{ fg = M.colors.fg, bg = M.colors.bg }"),
        ("NormalNC", "{ fg = M.colors.fg, bg = M.colors.bg }"),
        ("NormalFloat", "{ fg = M.colors.fg, bg = M.colors.surface }"),
        (
            "FloatBorder",
            "{ fg = M.colors.border, bg = M.colors.surface }",
        ),
        ("Cursor", "{ fg = M.colors.bg, bg = M.colors.primary }"),
        ("CursorLine", "{ bg = M.colors.surface }"),
        ("CursorLineNr", "{ fg = M.colors.primary, bold = true }"),
        ("Visual", "{ bg = M.colors.selected, fg = M.colors.fg }"),
        ("Search", "{ bg = M.colors.primary, fg = M.colors.bg }"),
        ("IncSearch", "{ bg = M.colors.secondary, fg = M.colors.bg }"),
        ("LineNr", "{ fg = M.colors.muted }"),
        ("SignColumn", "{ fg = M.colors.muted, bg = M.colors.bg }"),
        (
            "StatusLine",
            "{ fg = M.colors.fg, bg = M.colors.surface_alt }",
        ),
        (
            "StatusLineNC",
            "{ fg = M.colors.muted, bg = M.colors.surface }",
        ),
        ("WinSeparator", "{ fg = M.colors.border }"),
        ("Pmenu", "{ fg = M.colors.fg, bg = M.colors.surface_alt }"),
        (
            "PmenuSel",
            "{ fg = M.colors.bg, bg = M.colors.primary, bold = true }",
        ),
        ("PmenuSbar", "{ bg = M.colors.surface }"),
        ("PmenuThumb", "{ bg = M.colors.border }"),
        ("Comment", "{ fg = M.colors.muted, italic = true }"),
        ("Constant", "{ fg = M.colors.secondary }"),
        ("String", "{ fg = M.colors.success }"),
        ("Number", "{ fg = M.colors.warning }"),
        ("Boolean", "{ fg = M.colors.warning, bold = true }"),
        ("Identifier", "{ fg = M.colors.fg }"),
        ("Function", "{ fg = M.colors.primary, bold = true }"),
        ("Keyword", "{ fg = M.colors.primary, italic = true }"),
        ("Statement", "{ fg = M.colors.primary }"),
        ("Type", "{ fg = M.colors.secondary }"),
        ("Operator", "{ fg = M.colors.text }"),
        ("Special", "{ fg = M.colors.hover }"),
        (
            "Todo",
            "{ fg = M.colors.bg, bg = M.colors.warning, bold = true }",
        ),
        ("Error", "{ fg = M.colors.error, bold = true }"),
        ("ErrorMsg", "{ fg = M.colors.error, bold = true }"),
        ("WarningMsg", "{ fg = M.colors.warning }"),
        ("DiagnosticError", "{ fg = M.colors.error }"),
        ("DiagnosticWarn", "{ fg = M.colors.warning }"),
        ("DiagnosticInfo", "{ fg = M.colors.secondary }"),
        ("DiagnosticHint", "{ fg = M.colors.muted }"),
        (
            "DiffAdd",
            "{ fg = M.colors.success, bg = M.colors.surface }",
        ),
        (
            "DiffChange",
            "{ fg = M.colors.warning, bg = M.colors.surface }",
        ),
        (
            "DiffDelete",
            "{ fg = M.colors.error, bg = M.colors.surface }",
        ),
        ("Directory", "{ fg = M.colors.secondary, bold = true }"),
        ("Title", "{ fg = M.colors.primary, bold = true }"),
        (
            "MatchParen",
            "{ fg = M.colors.bg, bg = M.colors.secondary }",
        ),
    ];

    for (group, spec) in highlights {
        output.push_str(&format!("  hi(\"{group}\", {spec})\n"));
    }

    output.push_str("end\n\n");
    output.push_str("M.setup()\n\n");
    output.push_str("return M\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_a_loadable_module() {
        let lua = render(&theme());

        assert!(lua.contains("local M = {}"));
        assert!(lua.contains("bg = \"#0C0812\""));
        assert!(lua.contains("hi(\"Normal\", { fg = M.colors.fg"));
        assert!(lua.trim_end().ends_with("return M"));
    }

    #[test]
    fn validates_neovim_module() {
        assert!(Neovim.validate(&render(&theme())).is_ok());
        assert!(Neovim.validate("vim.g.colors_name = 'x'").is_err());
    }
}
