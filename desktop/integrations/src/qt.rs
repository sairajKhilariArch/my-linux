//! Qt application styling through a qt6ct/qt5ct colour scheme.
//!
//! Qt applies a colour scheme only when the platform theme is configured:
//!
//! ```text
//! QT_QPA_PLATFORMTHEME=qt6ct
//! ```

use theme_engine::{Color, LoadedTheme};

use crate::{Integration, RenderError, require};

pub struct Qt;

impl Integration for Qt {
    fn id(&self) -> &'static str {
        "qt"
    }

    fn name(&self) -> &'static str {
        "Qt (qt6ct/qt5ct)"
    }

    fn relative_path(&self) -> &'static str {
        "qt6ct/colors/my-linux.conf"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["qt6ct", "qt5ct", "qtpaths6", "qtpaths"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("qt", content, "[ColorScheme]")?;
        require("qt", content, "active_colors=")?;
        require("qt", content, "inactive_colors=")?;
        require("qt", content, "disabled_colors=")?;

        for key in ["active_colors", "inactive_colors", "disabled_colors"] {
            let line = content
                .lines()
                .find(|line| line.starts_with(key))
                .ok_or_else(|| RenderError::Invalid(format!("missing `{key}` line")))?;

            let values = line
                .split_once('=')
                .map(|(_, values)| values.trim())
                .unwrap_or_default();

            let count = values.split(',').count();

            if count != 21 {
                return Err(RenderError::Invalid(format!(
                    "`{key}` has {count} colours, Qt needs 21"
                )));
            }
        }

        Ok(())
    }
}

/// Qt writes colours as `#AARRGGBB`; the palette is fully opaque.
fn argb(color: Color) -> String {
    format!("#ff{:02X}{:02X}{:02X}", color.red, color.green, color.blue)
}

fn scheme(palette: &[Color; 21]) -> String {
    palette
        .iter()
        .map(|color| argb(*color))
        .collect::<Vec<String>>()
        .join(", ")
}

/// The 21 `QPalette` roles in the order qt5ct and qt6ct expect.
fn roles(theme: &LoadedTheme) -> [Color; 21] {
    let c = &theme.colors;

    [
        c.text,                      // WindowText
        c.surface,                   // Button
        c.surface_alt.lighten(0.15), // Light
        c.surface_alt,               // Midlight
        c.surface.darken(0.2),       // Dark
        c.border,                    // Mid
        c.text,                      // Text
        c.text.lighten(0.2),         // BrightText
        c.text,                      // ButtonText
        c.background,                // Base
        c.background,                // Window
        c.border.darken(0.3),        // Shadow
        c.primary,                   // Highlight
        c.background,                // HighlightedText
        c.secondary,                 // Link
        c.secondary.lighten(0.25),   // LinkVisited
        c.surface_alt,               // AlternateBase
        c.text_muted,                // NoRole
        c.surface_alt,               // ToolTipBase
        c.text,                      // ToolTipText
        c.text_muted,                // PlaceholderText
    ]
}

/// Generates a qt6ct/qt5ct colour scheme from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let active = roles(theme);

    let mut inactive = active;
    inactive[12] = theme.colors.primary.darken(0.35); // Highlight
    inactive[13] = theme.colors.text_muted; // HighlightedText

    let mut disabled = active;
    disabled[0] = theme.colors.text_muted;
    disabled[6] = theme.colors.text_muted;
    disabled[8] = theme.colors.text_muted;
    disabled[12] = theme.colors.border;
    disabled[13] = theme.colors.text_muted;

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n");
    output.push_str("# Copy to ~/.config/qt6ct/colors/my-linux.conf and select it in qt6ct,\n");
    output.push_str("# then export QT_QPA_PLATFORMTHEME=qt6ct.\n\n");
    output.push_str("[ColorScheme]\n");
    output.push_str(&format!("active_colors={}\n", scheme(&active)));
    output.push_str(&format!("inactive_colors={}\n", scheme(&inactive)));
    output.push_str(&format!("disabled_colors={}\n", scheme(&disabled)));

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_three_palettes_with_opaque_colours() {
        let conf = render(&theme());

        assert!(conf.contains("[ColorScheme]"));
        assert!(conf.contains("#ff0C0812"));
        assert!(conf.contains("#ffFF235A"));

        for key in ["active_colors", "inactive_colors", "disabled_colors"] {
            let line = conf
                .lines()
                .find(|line| line.starts_with(key))
                .expect("colour line should exist");

            assert_eq!(line.split(',').count(), 21, "{key} needs 21 roles");
        }
    }

    #[test]
    fn validates_qt_colour_scheme() {
        assert!(Qt.validate(&render(&theme())).is_ok());

        let short = "[ColorScheme]\nactive_colors=#ff000000\ninactive_colors=#ff000000\ndisabled_colors=#ff000000\n";

        assert!(Qt.validate(short).is_err());
    }
}
