//! Waybar CSS integration.

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Waybar;

impl Integration for Waybar {
    fn id(&self) -> &'static str {
        "waybar"
    }

    fn name(&self) -> &'static str {
        "Waybar"
    }

    fn relative_path(&self) -> &'static str {
        "waybar.css"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["waybar"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("waybar", content, "@define-color main-bg")?;
        require("waybar", content, "@define-color wb-act-bg")?;
        validate_braces(content)
    }

    fn reload_commands(&self) -> &'static [&'static [&'static str]] {
        &[&["killall", "-SIGUSR2", "waybar"]]
    }
}

/// Generates Waybar CSS from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;
    let hex = |color: theme_engine::Color| color.to_hex();

    let mut output = String::new();

    output.push_str("/* Generated by My Linux Theme Engine. Do not edit manually. */\n\n");
    output.push_str(&format!(
        "@define-color bar-bg {};\n",
        hex(colors.background)
    ));
    output.push_str(&format!(
        "@define-color main-bg {};\n",
        hex(colors.background)
    ));
    output.push_str(&format!("@define-color main-fg {};\n", hex(colors.text)));
    output.push_str(&format!(
        "@define-color wb-act-bg {};\n",
        hex(colors.primary)
    ));
    output.push_str(&format!(
        "@define-color wb-act-fg {};\n",
        hex(colors.background)
    ));
    output.push_str(&format!(
        "@define-color wb-hvr-bg {};\n",
        hex(colors.secondary)
    ));
    output.push_str(&format!(
        "@define-color wb-hvr-fg {};\n\n",
        hex(colors.background)
    ));

    output.push_str(&format!("@define-color surface {};\n", hex(colors.surface)));
    output.push_str(&format!(
        "@define-color surface-alt {};\n",
        hex(colors.surface_alt)
    ));
    output.push_str(&format!("@define-color border {};\n", hex(colors.border)));
    output.push_str(&format!(
        "@define-color text-muted {};\n",
        hex(colors.text_muted)
    ));
    output.push_str(&format!("@define-color success {};\n", hex(colors.success)));
    output.push_str(&format!("@define-color warning {};\n", hex(colors.warning)));
    output.push_str(&format!("@define-color error {};\n", hex(colors.error)));
    output.push_str(&format!(
        "@define-color selected {};\n\n",
        hex(colors.selected)
    ));

    output.push_str(&format!(
        "* {{\n    font-family: \"{}\", monospace;\n    font-size: {}px;\n    border: none;\n    border-radius: {}px;\n    min-height: 0;\n}}\n\n",
        theme.typography.mono_family, theme.typography.font_size, theme.metrics.radius
    ));

    output.push_str(
        r#"window#waybar {
    background: @main-bg;
    color: @main-fg;
}

window#waybar.hidden {
    opacity: 0.2;
}

#workspaces button {
    background: transparent;
    color: @text-muted;
    padding: 0 8px;
    margin: 2px 2px;
}

#workspaces button.active {
    background: @wb-act-bg;
    color: @wb-act-fg;
}

#workspaces button:hover {
    background: @wb-hvr-bg;
    color: @wb-hvr-fg;
}

#workspaces button.urgent {
    background: @error;
    color: @main-bg;
}

#clock,
#battery,
#cpu,
#memory,
#network,
#pulseaudio,
#tray,
#backlight,
#custom-power,
#idle_inhibitor {
    padding: 0 10px;
    color: @main-fg;
}

#battery.charging {
    color: @success;
}

#battery.warning {
    color: @warning;
}

#battery.critical {
    color: @error;
}

#pulseaudio.muted {
    color: @text-muted;
}

tooltip {
    background: @surface;
    border: 1px solid @border;
}

tooltip label {
    color: @main-fg;
}

menu {
    background: @surface-alt;
    border: 1px solid @border;
    color: @main-fg;
}
"#,
    );

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_theme_colours_and_states() {
        let css = render(&theme());

        assert!(css.contains("@define-color main-bg #0C0812;"));
        assert!(css.contains("@define-color wb-act-bg #FF235A;"));
        assert!(css.contains("@define-color wb-hvr-bg #00E6FF;"));
        assert!(css.contains("@define-color success #39FF88;"));
        assert!(css.contains("#workspaces button.active"));
        assert!(css.contains("#battery.critical"));
        assert!(css.contains("tooltip"));
    }

    #[test]
    fn validates_generated_css() {
        let css = render(&theme());

        assert!(Waybar.validate(&css).is_ok());
        assert!(Waybar.validate("/* nothing */").is_err());
        assert!(
            Waybar
                .validate("@define-color main-bg #000; @define-color wb-act-bg #fff; }")
                .is_err()
        );
    }

    #[test]
    fn reports_the_destination_and_program() {
        assert_eq!(Waybar.relative_path(), "waybar.css");
        assert_eq!(Waybar.programs(), &["waybar"]);
    }
}
