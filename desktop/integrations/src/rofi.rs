//! Rofi RASI integration.

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require, validate_braces};

pub struct Rofi;

impl Integration for Rofi {
    fn id(&self) -> &'static str {
        "rofi"
    }

    fn name(&self) -> &'static str {
        "Rofi"
    }

    fn relative_path(&self) -> &'static str {
        "rofi/theme.rasi"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["rofi"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("rofi", content, "element selected")?;
        require("rofi", content, "window {")?;
        validate_braces(content)
    }

    fn reload_commands(&self) -> &'static [&'static [&'static str]] {
        // Rofi reads its configuration on the next launch.
        &[]
    }
}

/// Generates a Rofi RASI theme from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;
    let hex = |color: theme_engine::Color| color.to_hex();

    let mut output = String::new();

    output.push_str("/* Generated by My Linux Theme Engine. Do not edit manually. */\n\n");

    output.push_str("* {\n");
    output.push_str(&format!(
        "    background-color: {};\n",
        hex(colors.background)
    ));
    output.push_str(&format!("    text-color: {};\n", hex(colors.text)));
    output.push_str("    border: 0;\n");
    output.push_str("    margin: 0;\n");
    output.push_str("    padding: 0;\n");
    output.push_str("    spacing: 0;\n");
    output.push_str("}\n\n");

    output.push_str("window {\n");
    output.push_str(&format!(
        "    background-color: {};\n",
        hex(colors.background)
    ));
    output.push_str(&format!(
        "    border: 2px;\n    border-color: {};\n",
        hex(colors.border)
    ));
    output.push_str("    border-radius: 12px;\n");
    output.push_str("    width: 40%;\n");
    output.push_str("}\n\n");

    output.push_str("mainbox {\n");
    output.push_str("    padding: 12px;\n");
    output.push_str("    spacing: 8px;\n");
    output.push_str("}\n\n");

    output.push_str("inputbar {\n");
    output.push_str(&format!("    background-color: {};\n", hex(colors.surface)));
    output.push_str(&format!("    text-color: {};\n", hex(colors.text)));
    output.push_str("    border-radius: 8px;\n");
    output.push_str("    padding: 8px;\n");
    output.push_str("}\n\n");

    output.push_str("prompt {\n");
    output.push_str(&format!("    text-color: {};\n", hex(colors.primary)));
    output.push_str("    padding: 0 8px 0 0;\n");
    output.push_str("}\n\n");

    output.push_str("listview {\n");
    output.push_str("    lines: 10;\n");
    output.push_str("    columns: 1;\n");
    output.push_str("    spacing: 4px;\n");
    output.push_str("    scrollbar: false;\n");
    output.push_str("}\n\n");

    output.push_str("element {\n");
    output.push_str("    padding: 8px;\n");
    output.push_str("    border-radius: 8px;\n");
    output.push_str(&format!("    background-color: {};\n", hex(colors.surface)));
    output.push_str(&format!("    text-color: {};\n", hex(colors.text_muted)));
    output.push_str("}\n\n");

    output.push_str("element selected {\n");
    output.push_str(&format!("    background-color: {};\n", hex(colors.primary)));
    output.push_str(&format!("    text-color: {};\n", hex(colors.background)));
    output.push_str("}\n\n");

    output.push_str("element-text, element-icon {\n");
    output.push_str("    background-color: inherit;\n");
    output.push_str("    text-color: inherit;\n");
    output.push_str("    vertical-align: 0.5;\n");
    output.push_str("}\n");

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("cyberpunk")
            .expect("cyberpunk should load")
    }

    #[test]
    fn renders_rasi_theme() {
        let rasi = render(&theme());

        assert!(rasi.contains("window {"));
        assert!(rasi.contains("element selected {"));
        assert!(rasi.contains("#FF235A"));
        assert!(rasi.contains("#0C0812"));
    }

    #[test]
    fn validates_rasi_output() {
        assert!(Rofi.validate(&render(&theme())).is_ok());
        assert!(Rofi.validate("window { }").is_err());
        assert!(Rofi.validate("").is_err());
    }

    #[test]
    fn uses_the_expected_path() {
        assert_eq!(Rofi.relative_path(), "rofi/theme.rasi");
    }
}
