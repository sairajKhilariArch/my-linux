//! Btop system monitor theme.
//!
//! Btop reads themes from `~/.config/btop/themes/`; the theme is selected with
//! `color_theme = "my-linux"` in `btop.conf`.

use theme_engine::LoadedTheme;

use crate::{Integration, RenderError, require};

pub struct Btop;

impl Integration for Btop {
    fn id(&self) -> &'static str {
        "btop"
    }

    fn name(&self) -> &'static str {
        "Btop system monitor"
    }

    fn relative_path(&self) -> &'static str {
        "btop/themes/my-linux.theme"
    }

    fn programs(&self) -> &'static [&'static str] {
        &["btop"]
    }

    fn render(&self, theme: &LoadedTheme) -> String {
        render(theme)
    }

    fn validate(&self, content: &str) -> Result<(), RenderError> {
        require("btop", content, "theme[main_bg]")?;
        require("btop", content, "theme[selected_bg]")?;
        require("btop", content, "theme[div_line]")?;

        for line in content.lines() {
            let line = line.trim();

            if line.is_empty() || line.starts_with('#') {
                continue;
            }

            let valid = line.starts_with("theme[")
                && line.contains("]=")
                && line.contains('"')
                && line.ends_with('"');

            if !valid {
                return Err(RenderError::Invalid(format!(
                    "unexpected theme line `{line}`"
                )));
            }
        }

        Ok(())
    }
}

/// Generates a Btop theme from the active theme.
pub fn render(theme: &LoadedTheme) -> String {
    let c = &theme.colors;

    let bg = c.background.to_hex();
    let surface = c.surface.to_hex();
    let fg = c.text.to_hex();
    let muted = c.text_muted.to_hex();
    let border = c.border.to_hex();
    let primary = c.primary.to_hex();
    let secondary = c.secondary.to_hex();
    let success = c.success.to_hex();
    let warning = c.warning.to_hex();
    let error = c.error.to_hex();

    let entries: [(&str, &str); 40] = [
        ("main_bg", &bg),
        ("main_fg", &fg),
        ("title", &fg),
        ("hi_fg", &primary),
        ("selected_bg", &primary),
        ("selected_fg", &bg),
        ("inactive_fg", &muted),
        ("proc_misc", &secondary),
        ("cpu_box", &primary),
        ("mem_box", &success),
        ("net_box", &secondary),
        ("proc_box", &primary),
        ("div_line", &border),
        ("temp_start", &success),
        ("temp_mid", &warning),
        ("temp_end", &error),
        ("cpu_start", &success),
        ("cpu_mid", &warning),
        ("cpu_end", &error),
        ("free_start", &success),
        ("free_mid", &warning),
        ("free_end", &error),
        ("cached_start", &secondary),
        ("cached_mid", &secondary),
        ("cached_end", &secondary),
        ("available_start", &warning),
        ("available_mid", &warning),
        ("available_end", &warning),
        ("used_start", &error),
        ("used_mid", &error),
        ("used_end", &error),
        ("download_start", &success),
        ("download_mid", &success),
        ("download_end", &success),
        ("upload_start", &secondary),
        ("upload_mid", &secondary),
        ("upload_end", &secondary),
        ("process_start", &primary),
        ("process_mid", &primary),
        ("process_end", &primary),
    ];

    let mut output = String::new();

    output.push_str("# Generated by My Linux Theme Engine. Do not edit manually.\n");
    output.push_str("# Copy to ~/.config/btop/themes/my-linux.theme and set\n");
    output.push_str("#   color_theme = \"my-linux\"\n");
    output.push_str(&format!("# Panel base colour: {surface}\n\n"));

    for (key, color) in entries {
        output.push_str(&format!("theme[{key}]=\"{color}\"\n"));
    }

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::Registry;

    fn theme() -> LoadedTheme {
        Registry::new(vec!["../../themes".into()])
            .load("minimal")
            .expect("minimal should load")
    }

    #[test]
    fn renders_every_required_key() {
        let conf = render(&theme());

        assert!(conf.contains("theme[main_bg]=\"#"));
        assert!(conf.contains("theme[selected_bg]=\"#"));
        assert!(conf.contains("theme[div_line]=\"#"));
        assert_eq!(
            conf.lines()
                .filter(|line| line.starts_with("theme["))
                .count(),
            40
        );
    }

    #[test]
    fn validates_btop_theme() {
        assert!(Btop.validate(&render(&theme())).is_ok());
        assert!(Btop.validate("theme[main_bg]=#fff\n").is_err());
    }
}
