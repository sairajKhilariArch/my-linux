use theme_engine::loader::LoadedTheme;

/// Generates Waybar CSS from the active theme.
pub fn render_waybar_css(theme: &LoadedTheme) -> String {
    let colors = &theme.colors;

    format!(
        r#"/* Generated by My Linux Theme Engine. Do not edit manually. */

@define-color bar-bg {background};
@define-color main-bg {background};
@define-color main-fg {text};

@define-color wb-act-bg {primary};
@define-color wb-act-fg {background};

@define-color wb-hvr-bg {secondary};
@define-color wb-hvr-fg {background};
"#,
        background = colors.background.to_hex(),
        text = colors.text.to_hex(),
        primary = colors.primary.to_hex(),
        secondary = colors.secondary.to_hex(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use theme_engine::loader::load_theme_by_name;

    #[test]
    fn generates_cyberpunk_waybar_css() {
        let theme =
            load_theme_by_name("../../themes", "cyberpunk").expect("Cyberpunk theme should load");

        let css = render_waybar_css(&theme);

        assert!(css.contains("@define-color main-bg #0C0812;"));
        assert!(css.contains("@define-color main-fg #FFF0FA;"));
        assert!(css.contains("@define-color wb-act-bg #FF235A;"));
    }
}
